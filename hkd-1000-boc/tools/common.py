"""
Shared helpers for the HK$1,000 (Bank of China (Hong Kong), 2018 Series) tools: note geometry, alpha cut-outs with clean edges, framing a
cut-out onto its page box, and writing the page's boxes / masks.

Note space: the page places everything in a 720 x 320 "note space" over the whole note (data.js);
the working artwork is 2880 x 1440, so one note unit is 4 px across and 4.5 px down.
"""
import json, os
import numpy as np
import cv2
from PIL import Image
from scipy import ndimage

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = {'front': 'hkd-1000-boc-front.png', 'back': 'hkd-1000-boc-back.png'}
VB_W, VB_H = 720, 320
LAYERS = os.path.join(ROOT, 'assets', 'layers')
OVR = os.path.join(ROOT, 'assets', 'overrides')
CROPS = os.path.join(ROOT, 'feature-crops')
BOXES_JSON = os.path.join(ROOT, 'assets', 'boxes.json')


def load(side):
    return np.asarray(Image.open(os.path.join(ROOT, SRC[side])).convert('RGB')).astype(np.float32)


def scale(img):
    h, w = img.shape[:2]
    return w / VB_W, h / VB_H


def px(img, box):
    """note-unit box [x, y, w, h] -> pixel slice bounds (x0, y0, x1, y1)"""
    sx, sy = scale(img)
    x, y, w, h = box
    return (int(round(x * sx)), int(round(y * sy)), int(round((x + w) * sx)), int(round((y + h) * sy)))


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0, 1)
    return t * t * (3 - 2 * t)


def keep_components(mask, min_area=40, keep=None):
    """drop specks; `keep(stats_row, centroid)` decides per component when given"""
    m = (mask > 0.5).astype(np.uint8)
    n, lab, st, cen = cv2.connectedComponentsWithStats(m, 8)
    out = np.zeros(m.shape, bool)
    for k in range(1, n):
        if st[k, cv2.CC_STAT_AREA] < min_area:
            continue
        if keep is not None and not keep(st[k], cen[k]):
            continue
        out |= lab == k
    return out


def fill_holes(m):
    return ndimage.binary_fill_holes(m)


def soft_edge(binary, sigma=0.9):
    """binary mask -> anti-aliased alpha with a ~1-2 px edge (no haze: inside 1, outside 0)"""
    a = cv2.GaussianBlur(binary.astype(np.float32), (0, 0), sigma)
    return np.clip((a - 0.5) * 2.0 + 0.5, 0, 1)


def defringe(rgb, alpha, solid=0.92):
    """edge pixels take the colour of the nearest solid pixel, so no paper-coloured halo shows
    when the cut-out sits on a dark or blurred background"""
    inner = alpha >= solid
    if not inner.any():
        return rgb
    _, (iy, ix) = ndimage.distance_transform_edt(~inner, return_indices=True)
    out = rgb.copy()
    edge = ~inner
    out[edge] = rgb[iy[edge], ix[edge]]
    return out


def colour_to_alpha(rgb, paper, gain=1.25, floor=0.05):
    """GIMP-style colour-to-alpha: remove the paper tone, keep the ink printed on it"""
    bg = np.maximum(paper.astype(np.float32), 1.0)
    a_dark = (bg - rgb) / bg
    a_lite = (rgb - bg) / np.maximum(255 - bg, 1)
    a = np.maximum(a_dark, a_lite).max(axis=2)
    a = np.clip((a - floor) / (1 - floor) * gain, 0, 1)
    safe = np.maximum(a, 1e-3)[..., None]
    col = np.clip((rgb - bg) / safe + bg, 0, 255)
    return col, a


def paper_tone(rgb, pct=92):
    flat = rgb.reshape(-1, 3)
    lum = flat @ np.array([.299, .587, .114], np.float32)
    return np.median(flat[lum >= np.percentile(lum, pct)], axis=0)


_boxes = {}


def load_boxes():
    global _boxes
    if os.path.exists(BOXES_JSON):
        _boxes = json.load(open(BOXES_JSON))
    return _boxes


def save_piece(side, name, img, box, rgb, alpha, crop=True):
    """Frame a cut-out onto its page box and save it.
    rgb/alpha: full-resolution arrays for the pixel region of `box` (from px(img, box)).
    Writes assets/layers/<side>-<name>.png and feature-crops/<side>/<name>.png (trimmed).
    A hand-cleaned assets/overrides/<side>-<name>.png always wins."""
    os.makedirs(LAYERS, exist_ok=True)
    fn = f'{side}-{name}.png'
    rgba = np.dstack([np.clip(rgb, 0, 255), np.clip(alpha * 255, 0, 255)]).astype(np.uint8)
    im = Image.fromarray(rgba, 'RGBA')
    ov = os.path.join(OVR, fn)
    if os.path.exists(ov):
        im = Image.open(ov).convert('RGBA')
        print('  override wins:', fn)
    im.save(os.path.join(LAYERS, fn), optimize=True)
    _boxes[f'{side}-{name}'] = [round(v, 2) for v in box]
    if crop:
        os.makedirs(os.path.join(CROPS, side), exist_ok=True)
        bb = im.getchannel('A').point(lambda v: 255 if v > 4 else 0).getbbox()
        if bb:
            im.crop(bb).save(os.path.join(CROPS, side, f'{name}.png'), optimize=True)
    return im


def write_boxes():
    json.dump(_boxes, open(BOXES_JSON, 'w'), indent=1)
    with open(os.path.join(ROOT, 'assets', 'boxes.js'), 'w') as f:
        f.write('// generated by tools/hkd_features.py: where each extracted layer sits (720x320 note units)\n')
        f.write('const BOXES = ' + json.dumps(_boxes, indent=1) + ';\n')


def preview(paths, out, bg=(18, 16, 24), height=220):
    """contact sheet of cut-outs on a dark background, for checking edges"""
    ims = [Image.open(p).convert('RGBA') for p in paths]
    ims = [i.resize((max(1, int(i.width * height / i.height)), height), Image.LANCZOS) if i.height > height else i for i in ims]
    W = sum(i.width for i in ims) + 12 * (len(ims) + 1)
    H = max(i.height for i in ims) + 24
    sheet = Image.new('RGBA', (W, H), bg + (255,))
    x = 12
    for i in ims:
        sheet.alpha_composite(i, (x, 12))
        x += i.width + 12
    sheet.convert('RGB').save(out)
