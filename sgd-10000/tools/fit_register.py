"""
Fit the see-through register: where the reverse's gold Merlion fill lands on the obverse.

Seen through the paper the reverse is mirrored. The mirrored fill is scaled and moved until it
best covers the inside of the obverse outline (searching scale on both axes and position, scored
by overlap / IoU of the two shapes). The fitted box is written into assets/boxes.js as
"register-ghost" (note units, the same convention as every other layer box).

Run: python tools/fit_register.py
"""
import os, sys, json, re
import numpy as np
import cv2
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import extract_features as EF  # noqa: E402

ROOT = EF.ROOT
K = 8                                                     # raster resolution: px per note unit


def main():
    boxes_js = os.path.join(ROOT, 'assets', 'boxes.js')
    src = open(boxes_js, encoding='utf8').read()
    boxes = json.loads(src[src.index('{'):src.rindex('}') + 1])

    # obverse: the inside of the traced outline
    front_poly = next(r for r in EF.REGIONS if (r[1], r[0]) == ('front', 'lion-head-outline'))[4]
    fx0, fy0 = 140, 200
    canvas = np.zeros((110 * K, 110 * K), np.uint8)
    cv2.fillPoly(canvas, [np.array([((x - fx0) * K, (y - fy0) * K) for x, y in front_poly], np.int32)], 255)

    # reverse fill, mirrored, from the page layer (its frame = boxes['back-lion-head'])
    bx, by, bw, bh = boxes['back-lion-head']
    fill = Image.open(os.path.join(ROOT, 'assets', 'layers', 'back-lion-head.png')).convert('RGBA')
    a = np.asarray(fill.getchannel('A').transpose(Image.FLIP_LEFT_RIGHT))
    a = cv2.resize(a, (int(bw * K), int(bh * K)), interpolation=cv2.INTER_AREA)
    a = (a > 60).astype(np.uint8) * 255
    ys, xs = np.nonzero(a)
    a = a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]   # the fill itself, trimmed
    trim_x, trim_y = xs.min() / K, ys.min() / K           # where the trimmed fill starts in its frame

    fys, fxs = np.nonzero(canvas)
    target_w, target_h = fxs.max() - fxs.min(), fys.max() - fys.min()
    best = (-1, None)
    for kw in np.linspace(0.88, 1.08, 21):
        for kh in np.linspace(0.88, 1.08, 21):
            w, h = int(target_w * kw), int(target_h * kh)
            t = cv2.resize(a, (w, h), interpolation=cv2.INTER_NEAREST).astype(np.float32) / 255
            # overlap score: sum of canvas under the template, minus template outside the canvas
            cf = canvas.astype(np.float32) / 255
            inter = cv2.matchTemplate(cf, t, cv2.TM_CCORR)
            iou = inter / (t.sum() + cf.sum() - inter + 1e-6)
            _, score, _, (mx, my) = cv2.minMaxLoc(iou)
            if score > best[0]:
                best = (score, (mx, my, w, h))
    score, (mx, my, w, h) = best
    # placed fill (trimmed) in note units
    px0, py0 = fx0 + mx / K, fy0 + my / K
    sxk = w / a.shape[1]; syk = h / a.shape[0]
    # whole frame (mirrored image incl. its transparent margin) so the page can place the image as is
    frame_x = px0 - trim_x * sxk
    frame_y = py0 - trim_y * syk
    frame = [round(frame_x, 2), round(frame_y, 2), round(bw * sxk, 2), round(bh * syk, 2)]
    boxes['register-ghost'] = frame
    out = '// generated by tools/isolate_features.py: where each extracted layer sits (720x320 note units)' + chr(10)
    out += 'const BOXES = ' + json.dumps(boxes, indent=1) + ';' + chr(10)
    open(boxes_js, 'w', encoding='utf8').write(out)
    print(f'register fit: IoU {score:.3f}, frame {frame}')


if __name__ == '__main__':
    main()
